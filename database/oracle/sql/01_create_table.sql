-- 모든 테이블 삭제 (FK 자식 테이블부터 삭제)
DECLARE
    v_table_count NUMBER;
BEGIN
    SELECT COUNT(*) INTO v_table_count FROM user_tables WHERE table_name = 'REVIEW';
    IF v_table_count > 0 THEN
        EXECUTE IMMEDIATE 'DROP TABLE review CASCADE CONSTRAINTS';
    END IF;

END;
/
DROP TABLE order_item;
DROP TABLE orders;
DROP TABLE product;
DROP TABLE seller;
DROP TABLE member;

-- 부모 테이블 생성
CREATE TABLE member (
    member_id   VARCHAR2(15) NOT NULL,
    member_name VARCHAR2(20) NOT NULL,
    password    VARCHAR2(100) NOT NULL,
    email       VARCHAR2(50),
    joined_at   DATE DEFAULT SYSDATE NOT NULL,
    CONSTRAINT pk_member PRIMARY KEY (member_id),
    CONSTRAINT uq_member_email UNIQUE (email)
);

CREATE TABLE seller (
    seller_id     INT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    seller_name   VARCHAR2(200) NOT NULL,
    email         VARCHAR2(50 BYTE) NOT NULL,
    phone         VARCHAR2(15 BYTE) NOT NULL,
    registered_at DATE DEFAULT SYSDATE NOT NULL,
    CONSTRAINT pk_seller PRIMARY KEY (seller_id),
    CONSTRAINT uq_seller_email UNIQUE (email)
);

CREATE TABLE product (
    product_id   INT GENERATED BY DEFAULT AS IDENTITY,
    product_name VARCHAR2(200) NOT NULL,
    price        INT NOT NULL,
    seller_id    INT NOT NULL,
    CONSTRAINT pk_product PRIMARY KEY (product_id),
    CONSTRAINT fk_product_seller FOREIGN KEY (seller_id) REFERENCES seller (seller_id)
);

CREATE TABLE orders (
    order_id   NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY,
    member_id  VARCHAR2(50 CHAR) NOT NULL,
    ordered_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT pk_orders PRIMARY KEY (order_id),
    CONSTRAINT fk_orders_member FOREIGN KEY (member_id) REFERENCES member (member_id)
);

-- 자식 테이블 생성
CREATE TABLE review (
    review_id   INT GENERATED BY DEFAULT AS IDENTITY,
    title      VARCHAR2(200) NOT NULL,
    content    CLOB NOT NULL,
    file_name  VARCHAR2(255),
    file_type  VARCHAR2(100),
    file_data  BLOB,
    writer     VARCHAR2(15) NOT NULL,
    written_at DATE DEFAULT SYSDATE NOT NULL,
    product_id INT NOT NULL,
    CONSTRAINT pk_review PRIMARY KEY (review_id),
    CONSTRAINT fk_review_member FOREIGN KEY (writer) REFERENCES member (member_id),
    CONSTRAINT fk_review_product FOREIGN KEY (product_id) REFERENCES product (product_id)
);

CREATE TABLE order_item (
    order_id   INT NOT NULL,
    product_id INT NOT NULL,
    quantity   INT NOT NULL,
    unit_price INT NOT NULL,
    CONSTRAINT pk_order_item PRIMARY KEY (order_id, product_id),
    CONSTRAINT fk_order_item_orders FOREIGN KEY (order_id) REFERENCES orders (order_id),
    CONSTRAINT fk_order_item_product FOREIGN KEY (product_id) REFERENCES product (product_id)
);

