-- 기존 테이블 삭제 (외래 키 자식 테이블부터 삭제)
DROP TABLE IF EXISTS review;
DROP TABLE IF EXISTS order_item;
DROP TABLE IF EXISTS orders;
DROP TABLE IF EXISTS product;
DROP TABLE IF EXISTS seller;
DROP TABLE IF EXISTS member;

-- schema.sql과 같은 PostgreSQL 테이블 정의
CREATE TABLE member (
    member_id VARCHAR(50) PRIMARY KEY,
    member_name VARCHAR(100) NOT NULL,
    password VARCHAR(255) NOT NULL,
    email VARCHAR(50),
    joined_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE seller (
    seller_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    seller_name VARCHAR(100) NOT NULL,
    email VARCHAR(50),
    phone VARCHAR(15),
    registered_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE product (
    product_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_name VARCHAR(200) NOT NULL,
    price INTEGER NOT NULL,
    seller_id BIGINT NOT NULL,
    CONSTRAINT fk_product_seller FOREIGN KEY (seller_id) REFERENCES seller (seller_id),
    CONSTRAINT ck_product_price CHECK (price >= 0)
);

CREATE TABLE orders (
    order_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id VARCHAR(50) NOT NULL,
    ordered_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_orders_member FOREIGN KEY (member_id) REFERENCES member (member_id)
);

CREATE TABLE order_item (
    order_id BIGINT NOT NULL,
    product_id BIGINT NOT NULL,
    quantity BIGINT NOT NULL,
    unit_price INTEGER NOT NULL,
    CONSTRAINT pk_order_item PRIMARY KEY (order_id, product_id),
    CONSTRAINT fk_order_item_orders FOREIGN KEY (order_id) REFERENCES orders (order_id),
    CONSTRAINT fk_order_item_product FOREIGN KEY (product_id) REFERENCES product (product_id),
    CONSTRAINT ck_order_item_price CHECK (unit_price >= 0),
    CONSTRAINT ck_order_item_quantity CHECK (quantity > 0)
);

CREATE TABLE review (
    review_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(200) NOT NULL,
    content TEXT NOT NULL,
    file_name VARCHAR(255),
    file_type VARCHAR(100),
    file_data BYTEA,
    writer VARCHAR(50) NOT NULL,
    written_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    product_id BIGINT NOT NULL,
    CONSTRAINT fk_review_member FOREIGN KEY (writer) REFERENCES member (member_id),
    CONSTRAINT fk_review_product FOREIGN KEY (product_id) REFERENCES product (product_id)
);
